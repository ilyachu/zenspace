async def generate_track(filename: str, text: str):
    out_path = os.path.join("public/audio/meditations", filename)
    print(f"Generating {filename}...")
    comm = edge_tts.Communicate(text, "ru-RU-DmitryNeural", rate="-15%", pitch="-3Hz")
    await comm.save(out_path)
    print(f"Done: {filename}")

async def main():
    for fn, txt in TRACKS.items():
        await generate_track(fn, txt)

if __name__ == "__main__":
    asyncio.run(main())
